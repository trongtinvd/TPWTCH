// index.js - the public Sim facade. Everything else in js/sim is internal. Sim.API is GENERATED from the registries,
// so a card can only name what the Sim really has (see validate.js).
Sim.boot(K => {
  const {
    addStatus,
    removeStatus,
    statusLines,
    logLines,
    describe,
    lifeOf,
    live,
    hasSt,
    has,
    isRevealed,
    attackedIds,
    cloudMap,
    abDef,
    hpOf,
    targetZones,
    dispatch,
    canPlay,
    canActivate,
    hasAction,
    actionsOf,
    apCount,
    apList,
    apOpen,
    gainAP,
    hasAP,
    spendAP,
    canPayExtra,
    recalc,
    atkOf,
    RULES,
    canAttack,
    totalDamage,
    freeSlots,
    targetColumns,
    colKeys,
    other,
    isPerm,
    condOk,
    condsMet,
    canSee,
    allowed,
    bonusOf,
    isUnusable,
    markUnusable,
    zoneBar,
    giveZoneHp,
    damageZone,
    ctl,
    observe,
    observeEvents,
    historyBytes,
  } = K;
  const REGISTRIES = {
    effects: K.OPS,
    costs: K.COSTS,
    requirements: K.REQS,
    targets: K.TARGETS,
    colTargets: K.COLTARGETS,
    zoneTargets: K.ZONETARGETS,
    targetings: K.TARGETINGS,
    riders: K.RIDERS,
    triggers: K.TRIGGERS,
    passives: K.PASSIVES,
    conds: K.COND,
    exConds: K.EXCOND,
    hpKinds: K.HPKINDS, // non-player things with HP
    values: K.VALUES, // counted values (Fx.count)
  };
  return {
    addStatus,
    removeStatus,
    statusLines,
    logLines,
    describe,
    lifeOf,
    live,
    hasSt,
    has,
    isRevealed,
    attackedIds,
    cloudMap,
    abDef,
    hpOf,
    targetZones,
    dispatch,
    canPlay,
    canActivate,
    hasAction,
    actionsOf,
    apCount,
    apList,
    apOpen,
    gainAP,
    hasAP,
    spendAP,
    canPayExtra,
    recalc,
    atkOf,
    RULES,
    canAttack,
    totalDamage,
    freeSlots,
    targetColumns,
    colKeys,
    other,
    isPerm,
    condOk,
    condsMet,
    canSee,
    allowed,
    bonusOf,
    isUnusable,
    markUnusable,
    zoneBar,
    giveZoneHp,
    damageZone,
    ctl,
    observe,
    observeEvents,
    historyBytes,
    hasKw: K.hasKw, // keyworded abilities
    choicePicks: K.choicePicks, // the legal selections of the pending choice (validation and highlighting)
    stopOn: K.stopOn, // is a stop on (defaults included)
    slotSeen: K.slotSeen, // may a player know what stands on a zone
    strikesBack: K.strikesBack, // the "Defender strike back" option
    HPKINDS: K.HPKINDS,
    actor: K.actor, // who must act now
    turnStage: K.turnStage, // the turn's stage: start, draw, main, combat, ending, end (js/sim/turn.js)
    turnGo: K.turnGo, // a turn transition (the only writer of the turn's fields)
    TURN: K.TURN, // the transitions and the stages each may start from
    optionsFor: K.optionsFor, // what one player may do now, as plain data (the bot reads only this)
    accepts: K.accepts, // would this command be accepted (the state is not changed)
    hpRefs: K.hpRefs,
    hpResolve: K.hpResolve,
    damageHp: K.damageHp,
    enterCombat: K.enterCombat,
    nonLethalHold: K.nonLethalHold,
    API: Object.fromEntries(Object.entries(REGISTRIES).map(([kind, reg]) => [kind, Object.keys(reg)])),
    create: K.createGame,
  };
});

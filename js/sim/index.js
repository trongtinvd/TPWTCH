// index.js - the public Sim facade. Everything else in js/sim is internal. Sim.API is GENERATED from the registries,
// so a card can only name what the Sim really has (see validate.js).
Sim.boot(K => {
  const {
    addStatus,
    removeStatus,
    statusLines,
    logLines,
    describe,
    lifeOf,
    live,
    hasSt,
    has,
    isRevealed,
    attackedIds,
    cloudMap,
    abDef,
    hpOf,
    targetZones,
    dispatch,
    canPlay,
    canActivate,
    hasAction,
    majorUsed,
    canPayExtra,
    recalc,
    atkOf,
    RULES,
    canAttack,
    totalDamage,
    freeSlots,
    targetColumns,
    colKeys,
    other,
    isPerm,
  } = K;
  const REGISTRIES = {
    effects: K.OPS,
    costs: K.COSTS,
    requirements: K.REQS,
    targets: K.TARGETS,
    colTargets: K.COLTARGETS,
    zoneTargets: K.ZONETARGETS,
    riders: K.RIDERS,
    triggers: K.TRIGGERS,
    passives: K.PASSIVES,
  };
  return {
    addStatus,
    removeStatus,
    statusLines,
    logLines,
    describe,
    lifeOf,
    live,
    hasSt,
    has,
    isRevealed,
    attackedIds,
    cloudMap,
    abDef,
    hpOf,
    targetZones,
    dispatch,
    canPlay,
    canActivate,
    hasAction,
    majorUsed,
    canPayExtra,
    recalc,
    atkOf,
    RULES,
    canAttack,
    totalDamage,
    freeSlots,
    targetColumns,
    colKeys,
    other,
    isPerm,
    API: Object.fromEntries(Object.entries(REGISTRIES).map(([kind, reg]) => [kind, Object.keys(reg)])),
    create: K.createGame,
  };
});
